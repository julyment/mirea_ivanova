package task_2;

import java.util.Scanner;

public class Cycle {
    public static void main(String[] args) {
        System.out.println("Введите n: ");
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();

        for (int i = 1; i <= n; i++){
            System.out.print(i + " ");
    }
    }
}
