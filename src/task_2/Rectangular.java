package task_2;

import java.awt.*;

public class Rectangular extends Shape {
    private int width;
    private int height;

    public Rectangular(Color color, int x, int y, int width, int height) {
        super(color, x, y);
        this.width = width;
        this.height = height;
    }

    @Override
    public void draw(Graphics g) {
        g.setColor(color);
        g.fillRect(x, y, width, height);
    }
}
